import * as fs from "fs";
import * as path from "path";

// ============================================
// 📝 ডকুমেন্ট তৈরি
// ============================================
function createDocument(title: string, content: string, format: string) {
  console.log("\n📄 ডকুমেন্ট তৈরি হচ্ছে...");

  let fileContent = "";
  let fileName = "";

  if (format === "html") {
    fileContent = `
<!DOCTYPE html>
<html>
<head>
    <meta charset="UTF-8">
    <title>${title}</title>
    <style>
        body { font-family: Arial, sans-serif; margin: 20px; }
        h1 { color: #333; }
        p { line-height: 1.6; }
    </style>
</head>
<body>
    <h1>${title}</h1>
    <div>${content}</div>
    <p style="margin-top: 30px; font-size: 12px; color: #999;">
        Generated by Simple Local Agent
    </p>
</body>
</html>`;
    fileName = `${title.replace(/\s+/g, "_")}.html`;
  } else if (format === "txt") {
    fileContent = `
${"=".repeat(50)}
${title.toUpperCase()}
${"=".repeat(50)}

${content}

Generated: ${new Date().toLocaleString()}
`;
    fileName = `${title.replace(/\s+/g, "_")}.txt`;
  }

  const outputPath = path.join(process.cwd(), fileName);
  fs.writeFileSync(outputPath, fileContent);

  console.log(`✅ ডকুমেন্ট সফল: ${outputPath}`);
  return outputPath;
}

// ============================================
// 📊 ডেটা প্রসেসিং
// ============================================
function processData(
  data: unknown[],
  operation: string,
  criteria?: string
) {
  console.log(`\n📊 ডেটা প্রসেসিং: ${operation}`);

  let result: unknown = data;

  if (operation === "filter" && criteria) {
    result = data.filter((item: unknown) => {
      const str = JSON.stringify(item).toLowerCase();
      return str.includes(criteria.toLowerCase());
    });
    console.log(`✅ ফিল্টার করা হয়েছে: ${(result as unknown[]).length} আইটেম`);
  } else if (operation === "sort") {
    result = [...data].sort((a: unknown, b: unknown) => {
      const aStr = JSON.stringify(a);
      const bStr = JSON.stringify(b);
      return aStr.localeCompare(bStr);
    });
    console.log(`✅ সর্ট করা হয়েছে`);
  } else if (operation === "count") {
    result = { total: (data as unknown[]).length };
    console.log(`✅ মোট আইটেম: ${(result as { total: number }).total}`);
  } else if (operation === "aggregate") {
    result = {
      total: (data as unknown[]).length,
      items: data,
      timestamp: new Date().toISOString(),
    };
    console.log(`✅ ডেটা এগ্রিগেট করা হয়েছে`);
  }

  return result;
}

// ============================================
// 🖼️ ইমেজ তথ্য (প্রসেসিং শিমুলেশন)
// ============================================
function processImage(imagePath: string, operation: string) {
  console.log(`\n🖼️ ইমেজ অপারেশন: ${operation}`);
  console.log(`📁 ফাইল: ${imagePath}`);

  // চেক করুন ফাইল আছে কিনা
  if (fs.existsSync(imagePath)) {
    const stats = fs.statSync(imagePath);
    console.log(`✅ ফাইল পাওয়া গেছে (${(stats.size / 1024).toFixed(2)} KB)`);
    console.log(`✅ ${operation} অপারেশন সিমুলেটেড`);
  } else {
    console.log(`⚠️ ফাইল পাওয়া যায়নি`);
  }

  return `${operation} সম্পন্ন`;
}

// ============================================
// 📅 ক্যালেন্ডার ইভেন্ট
// ============================================
function manageCalendar(action: string, eventTitle?: string) {
  console.log(`\n📅 ক্যালেন্ডার অ্যাকশন: ${action}`);

  let result = "";

  if (action === "create") {
    result = `✅ ইভেন্ট তৈরি: "${eventTitle}"`;
    console.log(result);
  } else if (action === "list") {
    result = `📋 ক্যালেন্ডার ইভেন্ট (আগামী ৭ দিন):
    1. দলীয় মিটিং - সোমবার, ১০:০০ AM
    2. প্রজেক্ট রিভিউ - বুধবার, ২:০০ PM
    3. ক্লায়েন্ট কল - শুক্রবার, ৩:০০ PM`;
    console.log(result);
  } else if (action === "delete") {
    result = `✅ ইভেন্ট ডিলিট করা হয়েছে`;
    console.log(result);
  }

  return result;
}

