// 📧 ইমেইল ড্রাফট
// ============================================
function sendEmail(
  to: string[],
  subject: string,
  body: string,
  action: string
) {
  console.log(`\n📧 ইমেইল ${action === "draft" ? "খসড়া" : "পাঠানো"} হচ্ছে...`);
  console.log(`📮 প্রাপক: ${to.join(", ")}`);
  console.log(`📋 বিষয়: ${subject}`);

  const emailContent = `
TO: ${to.join(", ")}
SUBJECT: ${subject}
DATE: ${new Date().toLocaleString()}
${"=".repeat(50)}

${body}

${"=".repeat(50)}
Status: ${action === "draft" ? "DRAFT - সংরক্ষিত" : "SENT - পাঠানো হয়েছে"}
`;

  const fileName = `email_${Date.now()}.txt`;
  const outputPath = path.join(process.cwd(), fileName);
  fs.writeFileSync(outputPath, emailContent);

  console.log(
    `✅ ইমেইল ${action === "draft" ? "সংরক্ষিত" : "পাঠানো হয়েছে"}: ${outputPath}`
  );
  return outputPath;
}

// ============================================
// 🎯 মেইন এজেন্ট ফাংশন
// ============================================
async function runAgent(task: string) {
  console.log("\n" + "=".repeat(60));
  console.log("🤖 SIMPLE LOCAL AGENT");
  console.log("=".repeat(60));
  console.log(`\n📝 আপনার কাজ: ${task}\n`);

  // টাস্ক বিশ্লেষণ এবং সম্পাদন
  const taskLower = task.toLowerCase();

  // ডকুমেন্ট তৈরি
  if (taskLower.includes("ডকুমেন্ট") || taskLower.includes("রিপোর্ট")) {
    createDocument(
      "মাসিক প্রতিবেদন",
      "এটি একটি স্বয়ংক্রিয়ভাবে তৈরি প্রতিবেদন যা আপনার কাজের সারাংশ ধারণ করে।",
      "html"
    );
  }

  // ডেটা প্রসেসিং
  if (taskLower.includes("ডেটা") || taskLower.includes("প্রসেস")) {
    const sampleData = [
      { id: 1, নাম: "পণ্য A", মূল্য: 100 },
      { id: 2, নাম: "পণ্য B", মূল্য: 200 },
      { id: 3, নাম: "পণ্য C", মূল্য: 150 },
    ];
    processData(sampleData, "filter", "পণ্য");
  }

  // ইমেজ প্রসেসিং
  if (taskLower.includes("ইমেজ") || taskLower.includes("ছবি")) {
    processImage("./sample-image.png", "resize");
  }

  // ক্যালেন্ডার
  if (taskLower.includes("ক্যালেন্ডার") || taskLower.includes("ইভেন্ট")) {
    manageCalendar("list");
    manageCalendar("create", "নতুন মিটিং");
  }

  // ইমেইল
  if (taskLower.includes("ইমেইল") || taskLower.includes("পাঠান")) {
    sendEmail(
      ["manager@example.com", "team@example.com"],
      "মাসিক প্রতিবেদন সম্পন্ন",
      "নমস্কার,\n\nমাসিক প্রতিবেদন সম্পন্ন হয়েছে। অনুগ্রহ করে আলোচনার জন্য সময় নির্ধারণ করুন।\n\nধন্যবাদ",
      "draft"
    );
  }

  console.log("\n" + "=".repeat(60));
  console.log("✅ সব কাজ সম্পন্ন!");
  console.log("=".repeat(60) + "\n");
}

